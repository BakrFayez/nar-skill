"""Unit tests for the independent-oracle harnesses in
tests/benchmarks/ (field round Area 7, F-25/F-26).

- The dexdump differential runs over the committed
  synthetic DEX fixtures whenever a dexdump binary can be
  located, and skips cleanly when it cannot.
- The native-inventory differential runs over the
  synthetic APK fixture unconditionally: its oracle is
  the in-harness ELF reader, which needs no external
  tool. The .dex fixtures are committed; the .apk
  fixture is not (the repo never commits APK binaries),
  so it is regenerated in place when absent — the
  builder is deterministic, and a clean checkout must
  not fail on a file only a previous local run created
  (field round P2).
- Planted-discrepancy tests prove the harnesses can FAIL:
  an expectation built from the pristine fixture is checked
  against an altered copy (and, at the compare-API level,
  against a deliberately offset fact set), and the harness
  must report a mismatch. A harness that cannot fail is
  not an oracle.
- The skip-behaviour test points the dexdump locator at
  nothing and requires an "unavailable" report, not an
  exception and not a pass.

Synthetic inputs only: every fixture is generated by
tests/benchmarks/build_oracle_fixtures.py. No real target
data is used, and the inventory results are labelled
SYNTHETIC by the harness itself.
"""
import copy
import importlib.util
import io
import zipfile
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
BENCH = ROOT / "tests" / "benchmarks"
FIXTURES = BENCH / "fixtures"
DEX_FIXTURES = ["oracle_basic.dex", "oracle_branches.dex",
                "oracle_multi.dex"]
APK_FIXTURE = FIXTURES / "oracle_inventory.apk"

EMPTY_ENV = {
    "NAR_DEXDUMP": "/nonexistent/dexdump",
    "ANDROID_HOME": "/nonexistent",
    "ANDROID_SDK_ROOT": "/nonexistent",
    "PATH": "/nonexistent",
    "HOME": "/nonexistent",
}


def _load(name):
    spec = importlib.util.spec_from_file_location(
        name, BENCH / (name + ".py"))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


oracle_dexdump = _load("oracle_dexdump")
oracle_inventory = _load("oracle_inventory")

# The .apk fixture is gitignored (never commit binaries),
# so a clean checkout lacks it while a worked-in tree has
# it from an earlier builder run. Regenerate the fixture
# set in place when it is absent: build_all is
# deterministic (byte-identical output, the committed
# .dex files included), so this changes nothing in a tree
# that already has the fixtures.
if not APK_FIXTURE.is_file():
    _load("build_oracle_fixtures").build_all(FIXTURES)

DEXDUMP = oracle_dexdump.locate_dexdump()
needs_dexdump = pytest.mark.skipif(
    DEXDUMP is None,
    reason="dexdump not located ($NAR_DEXDUMP, "
           "$ANDROID_HOME/$ANDROID_SDK_ROOT build-tools, "
           "PATH, conventional SDK dirs)")


# ------------------------------------------------------------------
# Fixtures themselves
# ------------------------------------------------------------------

def test_fixtures_present_and_small():
    for name in DEX_FIXTURES + ["oracle_inventory.apk"]:
        path = FIXTURES / name
        assert path.is_file(), name
        assert 0 < path.stat().st_size < 16 * 1024, name


# ------------------------------------------------------------------
# dexdump differential (oracle: the SDK dexdump binary)
# ------------------------------------------------------------------

@needs_dexdump
def test_dexdump_differential_dex_fixtures():
    for name in DEX_FIXTURES:
        report = oracle_dexdump.run_differential(
            FIXTURES / name, dexdump_path=DEXDUMP)
        assert report["status"] == "agree", \
            (name, report["diffs"])
        assert report["dex_files"][0]["totals"][
            "methods_defined"] >= 2


@needs_dexdump
def test_dexdump_differential_apk_fixture():
    report = oracle_dexdump.run_differential(
        APK_FIXTURE, dexdump_path=DEXDUMP)
    assert report["status"] == "agree", report["diffs"]
    assert [e["name"] for e in report["dex_files"]] == \
        ["classes.dex"]


# ------------------------------------------------------------------
# Inventory differential (oracle: in-harness ELF reader)
# ------------------------------------------------------------------

def test_inventory_differential_apk_fixture():
    report = oracle_inventory.run_inventory(APK_FIXTURE)
    assert report["label"] == "SYNTHETIC"
    assert report["status"] == "agree", report["diffs"]
    assert report["expected"]["library_count"] == 2
    families = report["expected"]["engine_jni"]
    assert sum(m["count"] for m in families.values()) == 3


# ------------------------------------------------------------------
# Planted discrepancies: the harnesses must be able to fail
# ------------------------------------------------------------------

def test_inventory_detects_planted_discrepancy(tmp_path):
    """One byte flipped in a planted JNI export name inside
    a copy of the fixture: nar-native / nar-engines then
    report one fewer JNI export than the pristine-fixture
    expectation, and the harness must say mismatch."""
    expected = oracle_inventory.build_expected(APK_FIXTURE)
    with zipfile.ZipFile(APK_FIXTURE) as zf:
        members = {n: zf.read(n) for n in zf.namelist()}
    jni_member = "lib/arm64-v8a/liboracle_jni.so"
    blob = bytearray(members[jni_member])
    pos = blob.index(b"Java_org_cocos2dx_lib_")
    blob[pos] = ord("X")
    members[jni_member] = bytes(blob)
    mutated = tmp_path / "mutated.apk"
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w") as zf:
        for name, data in members.items():
            zf.writestr(name, data)
    mutated.write_bytes(buf.getvalue())

    report = oracle_inventory.run_inventory(
        mutated, expected=expected)
    assert report["status"] == "mismatch", report
    assert any("JNI" in d for d in report["diffs"]), \
        report["diffs"]


def test_dexdump_compare_api_detects_offset():
    """A deliberately offset fact set (one instruction
    added, one header count bumped) must produce diffs
    through the dexdump harness's compare API, while the
    untampered set agrees with itself."""
    path = FIXTURES / "oracle_basic.dex"
    facts, failures = oracle_dexdump.nar_facts(path)
    assert failures == []
    assert oracle_dexdump.compare_facts(facts, facts) == []

    tampered = copy.deepcopy(facts)
    key = sorted(tampered["methods"])[0]
    tampered["methods"][key]["instruction_count"] += 1
    tampered["header"]["method_ids"] += 1
    diffs = oracle_dexdump.compare_facts(facts, tampered)
    assert any("instruction_count" in d for d in diffs), diffs
    assert any("method_ids" in d for d in diffs), diffs


def test_inventory_compare_api_detects_offset():
    expected = oracle_inventory.build_expected(APK_FIXTURE)
    actual = oracle_inventory.nar_actual(APK_FIXTURE)
    assert oracle_inventory.compare_inventory(
        expected, actual) == []
    actual["libraries"][
        "arm64-v8a/liboracle_jni.so"]["jni_exports"] = []
    diffs = oracle_inventory.compare_inventory(
        expected, actual)
    assert any("JNI exports" in d for d in diffs), diffs


# ------------------------------------------------------------------
# Skip behaviour: no dexdump -> unavailable, never a failure
# ------------------------------------------------------------------

def test_dexdump_unavailable_reports_and_skips():
    assert oracle_dexdump.locate_dexdump(EMPTY_ENV) is None
    report = oracle_dexdump.run_differential(
        FIXTURES / "oracle_basic.dex", env=EMPTY_ENV)
    assert report["status"] == "unavailable"
    if DEXDUMP is None:
        pytest.skip("dexdump unavailable on this machine; "
                    "the differential tests above skip too")
