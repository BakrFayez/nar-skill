"""corpus.py: labeled-corpus construction for accuracy
measurement (2.6.2 WS-E1).

Two corpora, always reported separately:

- Synthetic corpus: samples generated by the repo's own
  synthetic builders (tests/synthetic_fixtures.py and the
  framework-fixture set). Ground truth is the builder's
  intent — what the builder deliberately constructed —
  never a parser's output.
- Real corpus: local fixtures bound by ROLE through the
  fixtures manifest ($NAR_FIXTURES/manifest.env). Labels
  come from (a) role bindings whose family is known from
  prior verified analysis, and (b) CROSS-LABELING: a real
  fixture of one engine family is a real NEGATIVE for the
  other families' detectors, and a clean real fixture is a
  negative for protection attribution. The labeling data
  itself (which local file carries which label) lives
  LOCALLY with the fixtures, never in this repo; this
  module emits role labels and counts only.

Sample record (the labeling file FORMAT, schema 1):
    {id: stable string,
     analyzer: engine|format|protection|framework|
               endpoint|security|native,
     dataset: real|synthetic,
     role: manifest role or builder id (label only),
     expected: the ground-truth label,
     polarity: positive|negative,
     ground_truth_source: builder|cross-label|
                          prior-verified-analysis|construction,
     verification_status: verified|unverified}

A local labeling file is a JSON document
{"schema": 1, "samples": [sample, ...]} stored beside the
fixtures (e.g. $NAR_FIXTURES/labeling.json). The runner
(run_accuracy.py) merges it over the derived bindings;
samples whose role is not bound locally are skipped and
counted, never guessed.

Part of NAR (Nirous Android Reversing).
MIT License. See LICENSE in the repo root.
"""
import os

# Engine families used for cross-labeling. A fixture whose
# family is F is a positive for F and a negative for every
# other family in this list.
ENGINE_FAMILIES = ("Unity", "Unreal Engine", "Flutter",
                   "React Native", "Godot")

# Role -> engine family, from prior verified analysis
# (2.6.1 report section 6: 6/6 labeled positives detected).
# Role labels only; the file binding stays in the local
# manifest.
ROLE_ENGINE_FAMILY = {
    "FIX_UNITY": "Unity",
    "FIX_UNITY_BUNDLES": "Unity",
    "FIX_FLUTTER": "Flutter",
    "FIX_RN": "React Native",
    "FIX_GAME_UNREAL": "Unreal Engine",
    "FIX_GODOT_LOOSE": "Godot",
}

# Engine verdict names that count as a detection of each
# family (nar-engines canonical names).
FAMILY_VERDICTS = {
    "Unity": {"Unity (IL2CPP)", "Unity (Mono)"},
    "Unreal Engine": {"Unreal Engine"},
    "Flutter": {"Flutter"},
    "React Native": {"React Native"},
    "Godot": {"Godot"},
}

# Role -> container format (nar-input identification).
ROLE_FORMAT = {
    "FIX_APP": "apk", "FIX_GAME": "apk", "FIX_UNITY": "apk",
    "FIX_UNITY_BUNDLES": "apk", "FIX_FLUTTER": "apk",
    "FIX_RN": "apk", "FIX_GAME_UNREAL": "apk",
    "FIX_GODOT_LOOSE": "apk", "FIX_XAPK": "xapk",
    "FIX_GODOT_PCK": "godot-pck",
}

# Synthetic framework fixtures: builder stem -> verdict.
SYNTHETIC_FRAMEWORKS = {
    "xamarin": "Xamarin / .NET",
    "cordova": "Cordova (hybrid)",
    "capacitor": "Capacitor (hybrid)",
    "qt": "Qt for Android",
    "defold": "Defold",
    "renpy": "Ren'Py",
    "rpgmaker": "RPG Maker (web export)",
    "kivy": "Embedded Python",
}

# Synthetic format files: generated file -> format label.
SYNTHETIC_FORMATS = {
    "synthetic.dex": "dex",
    "libsynthetic.so": "elf",
    "synthetic.pck": "godot-pck",
    "synthetic.pak": "unreal-pak",
    "synthetic.utoc": "unreal-iostore",
}


def _sample(sample_id, analyzer, dataset, role, expected,
            polarity, source, status="verified"):
    return {"id": sample_id, "analyzer": analyzer,
            "dataset": dataset, "role": role,
            "expected": expected, "polarity": polarity,
            "ground_truth_source": source,
            "verification_status": status}


def real_engine_samples(roles_present):
    """Engine positives + cross-labeled negatives for the
    real roles actually bound locally."""
    samples = []
    labeled = {r: f for r, f in ROLE_ENGINE_FAMILY.items()
               if r in roles_present}
    for role, family in sorted(labeled.items()):
        samples.append(_sample(
            f"real-engine-{role}-positive", "engine", "real",
            role, family, "positive", "prior-verified-analysis"))
        for other in ENGINE_FAMILIES:
            if other != family:
                samples.append(_sample(
                    f"real-engine-{role}-negative-{other}",
                    "engine", "real", role, other, "negative",
                    "cross-label"))
    return samples


def real_format_samples(roles_present):
    return [_sample(f"real-format-{role}", "format", "real",
                    role, fmt, "positive",
                    "prior-verified-analysis")
            for role, fmt in sorted(ROLE_FORMAT.items())
            if role in roles_present]


def real_protection_samples(roles_present, clean_roles):
    """Positives: the protected role. Negatives: the clean
    set plus every other bound real role (cross-label: a
    fixture with no protection attribution recorded is a
    negative for attributed-packer detection)."""
    samples = []
    if "FIX_PAIRIP" in roles_present:
        samples.append(_sample(
            "real-protection-FIX_PAIRIP-positive",
            "protection", "real", "FIX_PAIRIP",
            "attributed-commercial-packer", "positive",
            "prior-verified-analysis"))
    negatives = set(clean_roles)
    negatives.update(r for r in roles_present
                     if r != "FIX_PAIRIP")
    for role in sorted(negatives):
        samples.append(_sample(
            f"real-protection-{role}-negative", "protection",
            "real", role, "attributed-commercial-packer",
            "negative", "cross-label"))
    return samples


def synthetic_framework_samples(stems_present):
    """Framework positives + cross-labeled negatives among
    the synthetic framework fixtures present locally."""
    samples = []
    present = {s: v for s, v in SYNTHETIC_FRAMEWORKS.items()
               if s in stems_present}
    for stem, verdict in sorted(present.items()):
        samples.append(_sample(
            f"synthetic-framework-{stem}-positive",
            "framework", "synthetic", stem, verdict,
            "positive", "builder"))
        for other_stem, other in sorted(present.items()):
            if other != verdict:
                samples.append(_sample(
                    f"synthetic-framework-{stem}-negative-"
                    f"{other_stem}", "framework", "synthetic",
                    stem, other, "negative", "cross-label"))
    return samples


def synthetic_format_samples(files_present):
    return [_sample(f"synthetic-format-{name}", "format",
                    "synthetic", name, fmt, "positive",
                    "builder")
            for name, fmt in sorted(SYNTHETIC_FORMATS.items())
            if name in files_present]


def synthetic_endpoint_samples():
    """Endpoint-classification samples constructed per
    class. The label follows from the construction itself
    (a URL carrying a credential parameter IS sensitive;
    a hostless string IS unverifiable; a DEX-sourced plain
    URL meets the documented 'dex-string' rule). This
    measures rule consistency against construction-defined
    ground truth — weaker than independent human labeling,
    and reported as such."""
    cases = [
        ("ep-sensitive-query", "https://api.example.com/v1?api_key=abcdef123456",
         [], "sensitive"),
        ("ep-sensitive-auth-path", "http://example.com/login",
         [], "sensitive"),
        ("ep-third-party", "https://www.google-analytics.com/collect",
         ["classes.dex"], "third-party"),
        ("ep-dex-string", "https://api.example.com/v1/items",
         ["classes.dex"], "dex-string"),
        ("ep-potential-native", "https://api.example.com/v1/items",
         ["lib/arm64-v8a/libnative.so"], "potential"),
        ("ep-unused-assets", "https://example.com/about",
         ["assets/web/page.html"], "unused-candidate"),
        ("ep-unverified-hostless", "not a url at all",
         ["classes.dex"], "unverified"),
        ("ep-unverified-relative", "/relative/path/only",
         ["classes.dex"], "unverified"),
    ]
    return [{"id": cid, "analyzer": "endpoint",
             "dataset": "synthetic", "role": cid,
             "url": url, "sources": sources,
             "expected": expected, "polarity": "positive",
             "ground_truth_source": "construction",
             "verification_status": "verified"}
            for cid, url, sources, expected in cases]


def load_local_labeling(fixtures_dir):
    """Read the optional local labeling file. Returns
    (samples, note). Absent file is a normal state."""
    path = os.path.join(fixtures_dir, "labeling.json")
    if not os.path.isfile(path):
        return [], "no local labeling file; derived role " \
                   "bindings + cross-labels only"
    import json
    try:
        with open(path, encoding="utf-8") as fh:
            doc = json.load(fh)
    except (OSError, ValueError) as e:
        return [], f"local labeling file unreadable: {e}"
    if doc.get("schema") != 1 or not isinstance(
            doc.get("samples"), list):
        return [], "local labeling file has an unsupported " \
                   "schema; ignored"
    return doc["samples"], f"merged {len(doc['samples'])} " \
                           "local labeling samples"
